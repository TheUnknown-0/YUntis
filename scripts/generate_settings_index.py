"""Builds SettingsSearchIndex.kt from the settings screens.

Every `title = stringResource(R.string.x)` / `label = stringResource(R.string.x)` (and the
`description = ...` right after it) becomes a search entry of the category whose screen shows it.
Run again after adding settings:  python scripts/generate_settings_index.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
UI = ROOT / "app/src/main/java/sh/lsx/untisx/ui"
OUT = UI / "screens/settings/SettingsSearchIndex.kt"

CATEGORIES = {
    "GENERAL": ["screens/settings/GeneralSettingsScreen.kt", "components/LanguageSettingsContent.kt", "notebook/NotebookExportImport.kt"],
    "APPEARANCE": ["screens/settings/AppearanceSettingsScreen.kt", "components/ThemeSettingsContent.kt", "components/WidgetStyleSettingsCard.kt"],
    "NOTIFICATIONS": [
        "components/NotificationSettingsContent.kt",
        "components/PlannerSettingsCards.kt",
        "components/AutomationSettingsCards.kt",
    ],
    "TIMETABLE": ["screens/settings/TimetableSettingsScreen.kt"],
    "CALENDAR": ["screens/settings/CalendarSettingsScreen.kt"],
}

TITLE = re.compile(r"\b(?:title|label)\s*=\s*stringResource\(R\.string\.(\w+)\)")
DESC = re.compile(r"\bdescription\s*=\s*stringResource\(R\.string\.(\w+)\)")
# chip and option texts: Text(stringResource(R.string.x)) right inside a label lambda
CHIP = re.compile(r"label\s*=\s*\{\s*Text\(stringResource\(R\.string\.(\w+)\)\)")

# dialog choices and preview captions are not settings of their own
SKIP = re.compile(r"^(notebook_import_choice_\w+|settings_preview_\w+)$")

entries = []
for category, files in CATEGORIES.items():
    seen = set()
    for rel in files:
        path = UI / rel
        if not path.exists():
            continue
        lines = path.read_text(encoding="utf-8").splitlines()
        for i, line in enumerate(lines):
            for m in list(TITLE.finditer(line)) + list(CHIP.finditer(line)):
                title = m.group(1)
                if title in seen or SKIP.match(title):
                    continue
                desc = None
                for nxt in lines[i + 1 : i + 6]:
                    d = DESC.search(nxt)
                    if d:
                        desc = d.group(1)
                        break
                    if TITLE.search(nxt):
                        break
                seen.add(title)
                entries.append((category, title, desc))

body = []
for category, title, desc in entries:
    d = f"R.string.{desc}" if desc else "0"
    body.append(f"    SettingsSearchEntry(SettingsCategory.{category}, R.string.{title}, {d}),")

OUT.write_text(
    "package sh.lsx.untisx.ui.screens.settings\n\n"
    "import sh.lsx.untisx.R\n\n"
    "// Generated by scripts/generate_settings_index.py, do not edit by hand.\n"
    "internal val settingsSearchIndex = listOf(\n" + "\n".join(body) + "\n)\n",
    encoding="utf-8",
)
print(f"{len(entries)} entries -> {OUT.relative_to(ROOT)}")
